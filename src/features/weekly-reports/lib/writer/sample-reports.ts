/** The samples as the style guide's "דוגמאות" section. */
export function samplesText(samples: readonly SampleReport[]): string {
  return samples
    .map(
      (sample, index) => `### דוגמה ${index + 1}
דף העובדות בקצרה: ${sample.facts}

player_text:
${sample.playerText}

parent_text:
${sample.parentText}`,
    )
    .join("\n\n");
}
